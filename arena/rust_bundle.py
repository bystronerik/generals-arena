"""
Package a Rust bot from ``bots/<name>/`` into a submission zip, and prove the
archive before it ships.

One archive comes out — sources, ``Cargo.lock``, vendored crates, and a
``build.sh`` running ``cargo build --release --offline`` — and the judge
compiles it at intake on its own toolchain. It is named
``<bot_id>-<content_hash>.zip`` through :func:`arena.bundle.default_output_path`,
the same call the Python bundles use, so an archive says on its face which
rated program it holds and two builds of different code cannot land on one
path. It is audited against the judge's limits through
:func:`arena.bundle.check_limits` — again the same code path as the Python bots,
so the two cannot drift — and then smoke-tested by extracting it, running its
``build.sh``, and driving scripted frames through its ``run.sh``.

This module is the shared half. Everything a bot differs in lives in a
:class:`RustBotSpec`, and each bot's ``tools/package_submission.py`` is that
spec plus ``raise SystemExit(main(SPEC))``. The split exists because a second
hand-written copy of this file would drift from the first within one change to
the judge's limits.

It sits in ``arena/`` rather than ``bots/_common/`` deliberately: the content
hash walk never leaves ``bots/``, so a shared packager here is outside every
bot's rated identity by construction, while ``bots/_common/`` is inside the
Python bots' closures.

**Nothing here may assume the shape of a dependency graph.** morpheus-rs vendors
zero crates and joe-rs vendors ninety-three; the file count is reported and
:func:`arena.bundle.check_limits` is the only enforcement.
"""
from __future__ import annotations

